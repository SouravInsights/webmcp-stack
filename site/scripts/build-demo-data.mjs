// Builds the landing page demo from a real OpenAPI spec excerpt, by running
// the actual webmcp-codegen pipeline in dry-run mode. What the page shows is
// what the CLI produces, because the CLI produced it.
//
// Run after changing site/public/demo/immich-excerpt.openapi.yaml or the generator:
//   node scripts/build-demo-data.mjs        (from site/)

import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { runGenerate } from "../../packages/codegen/dist/index.js";
import { tools } from "../../packages/codegen/dist/outputs/index.js";
import { openapi } from "../../packages/codegen/dist/sources/index.js";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");

// Generate into a scratch directory. The pipeline preserves a file's owned
// region when the file exists; correct for users, wrong here. The demo must
// show a pristine fresh run, never a scaffold preserved from an old version.
const scratch = await mkdtemp(join(tmpdir(), "webmcp-demo-"));

// dryRun: the demo builds from report.files alone and must never write
// into the site tree. This script is plain .mjs, so nothing type-checks
// the option name; say it in a comment on purpose.
const report = await runGenerate(
  {
    // Served from public/ so the hosted playground can load the same excerpt
    // the landing page's demo was built from.
    sources: [openapi({ spec: "public/demo/immich-excerpt.openapi.yaml" })],
    outputs: [tools({ outDir: join(scratch, "src/webmcp") })],
  },
  { cwd: site, dryRun: true, skipAudit: false, force: true },
);

// Tool files only. The barrel (index.ts) and runtime helper are noise here.
const toolFiles = new Map(
  report.files
    .filter((f) => f.path.endsWith(".webmcp.ts") && !f.path.endsWith("runtime.webmcp.ts"))
    .map((f) => [
      f.path
        .split("/")
        .pop()
        .replace(/\.webmcp\.ts$/, ""),
      f.contents,
    ]),
);

const demoTools = report.tools.map((tool) => {
  const [verb, ...rest] = tool.source.ref.split(" ");
  const contents = toolFiles.get(tool.name);
  if (!contents) throw new Error(`No generated file found for ${tool.name}`);
  return {
    name: tool.name,
    verb,
    path: rest.join(" "),
    summary: tool.description,
    sideEffect: tool.sideEffect,
    fileName: `${tool.name}.webmcp.ts`,
    fileCode: contents,
    findings: report.findings
      .filter((f) => f.tool === tool.name)
      .map((f) => ({ severity: f.level, message: f.message })),
  };
});

// The same tools shaped as the dashboard's UiState, so the landing page can
// mount the real dashboard UI (packages/codegen/src/dev/ui.ts) statically.
const dashboardState = {
  label: "immich-excerpt.openapi.yaml",
  outDir: "src/webmcp",
  tools: report.tools.map((tool) => {
    const [verb, ...rest] = tool.source.ref.split(" ");
    return {
      name: tool.name,
      description: tool.description,
      sideEffect: tool.sideEffect,
      enabled: tool.enabledByDefault,
      endpointRole: tool.endpointRole ?? "endpoint",
      piiInOutput: tool.piiInOutput ?? [],
      findings: report.findings
        .filter((f) => f.tool === tool.name)
        .map((f) => ({ level: f.level, message: f.message })),
      inputSchema: tool.inputSchema,
      serverUrl: tool.serverUrl,
      requiresAuth: tool.requiresAuth ?? false,
      verb,
      path: rest.join(" "),
      // The generated file, for the dashboard's per-tool source disclosure.
      source: toolFiles.has(tool.name)
        ? { fileName: `${tool.name}.webmcp.ts`, code: toolFiles.get(tool.name) }
        : undefined,
    };
  }),
  skipped: (report.skipped ?? []).map((s) => ({ ref: s.ref, reason: s.reason })),
  notes: report.notes ?? [],
};

const out = `// Generated by site/scripts/build-demo-data.mjs from the real
// webmcp-codegen pipeline. Do not edit by hand; re-run the script instead.

export interface DemoTool {
  name: string;
  verb: string;
  path: string;
  summary: string;
  sideEffect: "read" | "write" | "destructive";
  fileName: string;
  fileCode: string;
  findings: Array<{ severity: "warning" | "error"; message: string }>;
}

export const DEMO_SOURCE = {
  project: "Immich",
  blurb: "the open-source photo app",
  specUrl: "https://github.com/immich-app/immich/blob/main/open-api/immich-openapi-specs.json",
};

export const DEMO_TOOLS: DemoTool[] = ${JSON.stringify(demoTools, null, 2)};

// Shaped like UiState from packages/codegen/src/dev/ui.ts; the landing demo
// injects it into the real dashboard UI.
export const DASHBOARD_STATE = ${JSON.stringify(dashboardState, null, 2)};
`;

await writeFile(join(site, "lib/demo-data.ts"), out);
console.log(`Wrote lib/demo-data.ts with ${demoTools.length} tools from the Immich excerpt.`);
